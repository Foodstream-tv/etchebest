#!/usr/bin/env node
/**
 * Copies the translation keys the mobile app shares with the web front
 * (front-web/src/i18n/messages) into i18n/messages/shared.{fr,en}.ts so both
 * clients use exactly the same wording.
 *
 *   node scripts/sync-i18n.mjs
 *
 * Mobile-only keys live in i18n/messages/{fr,en}.ts and win over shared ones.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webDir = resolve(root, '../front-web/src/i18n/messages');
const outDir = resolve(root, 'i18n/messages');

const PREFIXES = [
  'common.',
  'nav.',
  'home.',
  'watch.',
  'replays.',
  'profile.',
  'auth.',
  'notifications.',
  'studio.',
  'broadcast.',
  'cook.',
];

const ENTRY = /^ {2}("(?:[^"\\]|\\.)+"):\s*("(?:[^"\\]|\\.)*"),\s*$/;

function extract(locale) {
  const lines = readFileSync(resolve(webDir, `${locale}.ts`), 'utf8').split('\n');
  const entries = [];
  for (const line of lines) {
    const match = ENTRY.exec(line);
    if (!match) continue;
    const key = JSON.parse(match[1]);
    if (PREFIXES.some((prefix) => key.startsWith(prefix))) {
      entries.push([key, match[2]]);
    }
  }
  return entries;
}

for (const locale of ['fr', 'en']) {
  const entries = extract(locale);
  const body = entries.map(([key, value]) => `    ${JSON.stringify(key)}: ${value},`).join('\n');
  const content = `// GENERATED by scripts/sync-i18n.mjs from front-web/src/i18n/messages/${locale}.ts — do not edit by hand.
// Mobile-only keys and overrides go in ./${locale}.ts.
const shared${locale === 'fr' ? 'Fr' : 'En'} = {
${body}
} as const;

export default shared${locale === 'fr' ? 'Fr' : 'En'};
`;
  writeFileSync(resolve(outDir, `shared.${locale}.ts`), content);
  console.log(`shared.${locale}.ts: ${entries.length} keys`);
}
